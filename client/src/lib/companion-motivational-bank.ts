/** Get a rich phrase for the given companion and context */
export function getCompanionQuote(
  companionId: CompanionId,
  context: MotivationContext,
  index?: number
): CompanionPhrase {
  const bank = companionId === "khadija" ? KHADIJA_QUOTES : YASSIN_QUOTES;
  const list = bank[context] || bank.home;
  if (index !== undefined) {
    return list[Math.abs(index) % list.length];
  }
  return list[Math.floor(Math.random() * list.length)];
}

/** Generates a fresh dynamic phrase with unique combinations */
export function generateFreshDynamicMotivation(companionId: CompanionId): string {
  const prefixes = DYNAMIC_PREFIXES[companionId];
  const messages = DYNAMIC_MESSAGES[companionId];
  const prefix = prefixes[Math.floor(Math.random() * prefixes.length)];
  const msg = messages[Math.floor(Math.random() * messages.length)];
  return `${prefix} ${msg}`;
}
